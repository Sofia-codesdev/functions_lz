import math

# Запрашиваем у пользователя радиус круга
radius = float(input("Введите радиус круга: "))

# Формула длины окружности: L = 2 * π * R
circumference = 2 * math.pi * radius

# Формула площади круга: S = π * R^2 (или π * R * R)
area = math.pi * (radius ** 2)

# Выводим результаты на экран, округляя до двух знаков после запятой
print(f"Длина окружности: {circumference:.2f}")
print(f"Площадь круга: {area:.2f}")
