# Запрашиваем строку
user_input = input("Введите строку для проверки на палиндром: ")


# Приводим к нижнему регистру
# Убираем все пробелы 
clean_string = user_input.lower().replace(" ", "")

# Сравниваем строку с её перевернутой версией
if clean_string == clean_string[::-1]:
    print("Да, это палиндром!")
else:
    print("Нет, это не палиндром.")